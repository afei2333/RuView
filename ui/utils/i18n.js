export class I18n {
  constructor() {
    const saved = this.getSavedLocale();
    this.locale = Object.hasOwn(translations, saved) ? saved : this.detectLocale();
    this.listeners = [];
  }

  init() {
    this.createSelector();
    this.applyTranslations();
  }

  detectLocale() {
    const lang = navigator.language?.toLowerCase() || 'en';
    if (lang.startsWith('zh')) return 'zh';
    if (lang.startsWith('pl')) return 'pl';
    return 'en';
  }

  getSavedLocale() {
    try { return localStorage.getItem('ruview-locale'); }
    catch { return null; }
  }

  saveLocale(locale) {
    try { localStorage.setItem('ruview-locale', locale); }
    catch { /* noop */ }
  }

  t(key, params = {}) {
    const dict = translations[this.locale] || translations.en;
    const message = Object.hasOwn(dict, key) ? dict[key]
      : Object.hasOwn(translations.en, key) ? translations.en[key] : key;
    return message.replace(/\{(\w+)\}/g, (match, name) =>
      Object.hasOwn(params, name) ? String(params[name]) : match);
  }

  status(value) {
    const key = `state.${value.toLowerCase()}`;
    const translated = this.t(key);
    return translated === key ? value.toUpperCase() : translated;
  }

  setLocale(locale) {
    if (!Object.hasOwn(translations, locale)) return;
    this.locale = locale;
    this.saveLocale(locale);
    this.applyTranslations();
    this.listeners.forEach(cb => { try { cb(locale); } catch { /* noop */ } });
  }

  onLocaleChange(callback) {
    this.listeners.push(callback);
    return () => {
      const i = this.listeners.indexOf(callback);
      if (i > -1) this.listeners.splice(i, 1);
    };
  }

  applyTranslations(root = document) {
    document.documentElement.setAttribute('lang', this.locale === 'zh' ? 'zh-CN' : this.locale);
    // Translate elements with data-i18n attribute
    root.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      el.textContent = this.t(key);
    });

    // Translate placeholders
    root.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      el.placeholder = this.t(key);
    });

    // Translate aria-labels
    root.querySelectorAll('[data-i18n-aria]').forEach(el => {
      const key = el.getAttribute('data-i18n-aria');
      el.setAttribute('aria-label', this.t(key));
    });

    for (const attribute of ['title', 'alt', 'label']) {
      root.querySelectorAll(`[data-i18n-${attribute}]`).forEach(el => {
        el.setAttribute(attribute, this.t(el.getAttribute(`data-i18n-${attribute}`)));
      });
    }

    // Update language selector
    const selector = document.getElementById('lang-selector');
    if (selector) selector.value = this.locale;
  }

  createSelector() {
    const wrapper = document.createElement('div');
    wrapper.className = 'lang-selector-wrap';
    wrapper.innerHTML = `
      <select id="lang-selector" class="lang-selector" aria-label="Language" data-i18n-aria="misc.language">
        <option value="en">EN</option>
        <option value="pl">PL</option>
        <option value="zh">中文</option>
      </select>
    `;

    const select = wrapper.querySelector('select');
    select.value = this.locale;
    select.addEventListener('change', () => this.setLocale(select.value));

    const headerInfo = document.querySelector('.header-info');
    if (headerInfo) {
      headerInfo.appendChild(wrapper);
    }
  }

  getAvailableLocales() {
    return Object.keys(translations);
  }

  dispose() {
    this.listeners = [];
  }
}

export const i18n = new I18n();
